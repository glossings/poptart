// The native device build's transformations (build/devices/native.mjs).
//
// What makes a device run in scsynth rather than in a worklet is almost entirely this file's
// three pure functions: the wrapper's state lifted into a struct, the registry the UGen looks a
// device up in, and the catalog the desktop engine reads to know that `synth("Plaits")` names a
// device at all. A mistake in any of them is a device that does not compile, or - worse - one
// that compiles and holds its state in one place for every instance, which is eight tracks
// sharing one Plaits. The compiler catches the first; these catch the second.

import test from 'node:test';
import assert from 'node:assert/strict';

import { structify, registrySource, catalogJson } from './build/devices/native.mjs';

/** A wrapper in the shape build-devices.mjs writes them: includes, a namespace, then the ABI. */
const WRAPPER = `// Generated by build/devices/build-devices.mjs - do not edit.
#include "thing/dsp/thing.h"

namespace {

Thing* g_thing = nullptr;
float g_out[2 * 128];
float g_params[32];
const int kFifo = 2048;
float g_fifo[kFifo];
int g_fifoCount = 0;

void Generate(int frames) {
  g_fifoCount = frames;
}

}  // namespace

extern "C" {

void pd_init(double sample_rate) {
  if (!g_thing) g_thing = new Thing();
  g_fifoCount = 0;
}

int pd_param_count() { return 3; }
int pd_max_block() { return 128; }
float* pd_in() { return g_out; }
float* pd_out() { return g_out; }
float* pd_params() { return g_params; }

static float g_note = 60.0f;

void pd_note_on(float note, float velocity) { g_note = note; }

void pd_process(int frames) {
  Generate(frames);
}

}
`;

test('structify lifts a wrapper into a struct without touching its DSP', () => {
  const out = structify(WRAPPER, { id: 'Thing' });

  // The includes stay at the top, outside everything.
  assert.ok(out.indexOf('#include "thing/dsp/thing.h"') < out.indexOf('struct Device'));
  assert.ok(out.includes('#include "pd-device.h"'));

  // One struct, in a namespace of its own, and no `extern "C"` block or stray namespace close
  // left behind inside it.
  assert.ok(out.includes('namespace pd_Thing {'));
  assert.ok(out.includes('struct Device {'));
  assert.ok(!out.includes('extern "C" {'));
  assert.ok(!out.includes('// namespace\n'), 'the inner namespace close should be gone');

  // The state is now members, and the DSP that reads it is unchanged.
  assert.ok(out.includes('float g_params[32];'));
  assert.ok(out.includes('void Generate(int frames) {\n  g_fifoCount = frames;\n}'));
  assert.ok(out.includes('void pd_process(int frames) {\n  Generate(frames);\n}'));

  // An array's size has to be a constant expression at struct scope...
  assert.ok(out.includes('static constexpr int kFifo = 2048;'));
  // ...and `static` on a member would be one copy for every instance, which is the bug this
  // whole transformation exists to prevent.
  // ...the one exception being the constants that became `static constexpr`, which is the only
  // `static` a member may have: shared by every instance because it is the same number in all.
  assert.ok(!/^static (?!constexpr)/m.test(out), 'no file-scope `static` state should survive into the struct');
  assert.ok(out.includes('float g_note = 60.0f;'));

  // What pd_init allocated is freed when an instance goes, or a slot filled and emptied all
  // evening leaks one device per fill.
  assert.ok(out.includes('~Device() {'));
  assert.ok(out.includes('delete g_thing;'));

  // And the one line that makes it reachable: a factory the registry can call.
  assert.ok(out.includes('extern "C" PdAny* pd_make_Thing() { return new PdAdapter<pd_Thing::Device>(); }'));
});

test('a wrapper says nothing about its kind: the adapter works it out from the device', () => {
  // Which of the note calls a device takes is detected from the struct (PdTakesNotes in
  // pd-device.h) rather than passed in here, because an effect's wrapper has no note functions
  // and the ducker is an effect that does - one flag could not say both.
  assert.ok(structify(WRAPPER, { id: 'Thing' }).includes('PdAdapter<pd_Thing::Device>'));
});

test('structify refuses a wrapper it does not recognise rather than compiling something else', () => {
  assert.throws(() => structify('#include "x.h"\nint main() {}\n', { id: 'X' }),
    /not shaped the way the native build expects/);
  assert.throws(() => structify(WRAPPER.replace('Thing* g_thing = nullptr;', 'Thing* g_thing;'), { id: 'Thing' }),
    /not initialised to nullptr/);
  assert.throws(() => structify(WRAPPER.replace('new Thing()', 'new float[64]'), { id: 'Thing' }),
    /allocates an array/);
});

const DEVICES = [
  {
    id: 'Thing',
    kind: 'synth',
    sidechain: false,
    params: [
      { id: 'engine', name: 'Engine', min: 0, max: 23, default: 8, step: 1, curve: 'lin', curveExp: 1, ui: 'enum', group: 'Model', rate: 'k', options: ['a', 'b'] },
      { id: 'cutoff', name: 'Cutoff', min: 20, max: 20000, default: 2000, step: 0, curve: 'exp', curveExp: 1, ui: 'knob', group: '', rate: 'a', unit: 'Hz' },
    ],
  },
  {
    id: 'Crosser',
    kind: 'fx',
    sidechain: true,
    params: [{ id: 'mix', name: 'Mix', min: 0, max: 1, default: 1, step: 0, curve: 'lin', curveExp: 1, ui: 'knob', group: '', rate: 'a' }],
  },
  {
    id: 'Dipper',
    kind: 'fx',
    sidechain: true,
    notes: true,
    params: [{ id: 'amount', name: 'Amount', min: 0, max: 1, default: 1, step: 0, curve: 'lin', curveExp: 1, ui: 'knob', group: '', rate: 'a' }],
  },
];

test('the registry carries each control as the position it rests at, and the device flags', () => {
  const src = registrySource(DEVICES);
  assert.ok(src.includes('extern "C" PdAny* pd_make_Thing();'));
  assert.ok(src.includes('extern "C" int pd_device_count() { return 3; }'));
  // An effect the descriptor says takes notes is marked as taking them, so the UGen passes a
  // routed track's notes on to it instead of dropping them for not being an instrument.
  assert.ok(src.includes('{ "Dipper", 0, 1, 1, 1, kDipperParams, &pd_make_Dipper },'));
  // An instrument (played by notes, no sidechain, two controls); and an effect that takes a
  // sidechain and no notes. The third column is whether notes reach it, which for an instrument
  // is always yes and for an effect is yes only where the descriptor says so (the ducker).
  assert.ok(src.includes('{ "Thing", 1, 1, 0, 2, kThingParams, &pd_make_Thing },'));
  assert.ok(src.includes('{ "Crosser", 0, 0, 1, 1, kCrosserParams, &pd_make_Crosser },'));
  // The default is written as a POSITION, because that is what the UGen holds a control at
  // until a pattern moves it: engine 8 of 0..23, and an exponential cutoff's 2000 Hz of
  // 20..20000, which is not at 10% of its travel.
  assert.ok(/\{ "engine", "Engine", 0.0f, 23.0f, 0\.34782/.test(src), src);
  const cutoff = src.match(/\{ "cutoff", "Cutoff", [^\n]*/)[0];
  assert.match(cutoff, /, 1 \},$/, 'an exponential control should carry curve 1');
  const position = Number(cutoff.split(', ')[4].replace('f', ''));
  assert.ok(Math.abs(position - Math.log(2000 / 20) / Math.log(20000 / 20)) < 1e-6,
    `2000 Hz should sit where the log sweep puts it, got ${position}`);
});

test('the catalog is what the desktop engine resolves a name against', () => {
  const doc = JSON.parse(catalogJson(DEVICES));
  // Sorted, so a rebuild that changed nothing changes no bytes.
  assert.deepEqual(doc.devices.map((d) => d.id), ['Crosser', 'Dipper', 'Thing']);
  const thing = doc.devices.find((d) => d.id === 'Thing');
  assert.equal(thing.kind, 'synth');
  assert.equal(thing.sidechain, false);
  assert.deepEqual(thing.params.map((p) => p.id), ['engine', 'cutoff']);
  // An enum's labels come along - a `.param("Engine", "Chord")` resolves against them - and the
  // real range and curve, since the readout and the knob are the same numbers as the browser's.
  assert.deepEqual(thing.params[0].options, ['a', 'b']);
  assert.equal(thing.params[1].curve, 'exp');
  assert.equal(thing.params[1].unit, 'Hz');
  assert.equal(doc.devices.find((d) => d.id === 'Crosser').sidechain, true);
});
